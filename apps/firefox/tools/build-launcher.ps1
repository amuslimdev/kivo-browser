<#
.SYNOPSIS
    بيبني Kivo.exe (Launcher.cs و Updater.cs) بالمفتاح العام اللي التحديثات لازم تكون موقّعة بيه (G6 في docs/FIREFOX.md).
.DESCRIPTION
    بالـ C# compiler اللي جاي مع Windows (.NET Framework 4). المفتاح بيدخل جوه الـ exe كـ ReleaseKey.PublicKeyXml.
.PARAMETER Output
    مسار Kivo.exe.
.PARAMETER PublicKey
    الافتراضي apps/firefox/release-key.pub.xml. اختبار التحديثات (updates-check.mjs) بيدّي مفتاح تجربة.
#>
param([Parameter(Mandatory)] [string] $Output, [string] $PublicKey)
. "$PSScriptRoot\common.ps1"
if (-not $PublicKey) { $PublicKey = Join-Path $FirefoxApp 'release-key.pub.xml' }

# المفتاح العام بس: Modulus و Exponent. لو حد غلط وادّى الخاص، مايدخلش جوه exe بيتوزّع.
$xml = (Get-Content $PublicKey -Raw).Trim()
if ($xml -notmatch '^<RSAKeyValue><Modulus>[A-Za-z0-9+/=]+</Modulus><Exponent>[A-Za-z0-9+/=]+</Exponent></RSAKeyValue>$') {
    throw "Not a public RSA key: $PublicKey"
}
$generated = Join-Path ([IO.Path]::GetTempPath()) "KivoReleaseKey-$PID.cs"
$code = "// Generated by build-launcher.ps1 from $(Split-Path $PublicKey -Leaf).`nstatic class ReleaseKey`n{`n    public const string PublicKeyXml = `"$xml`";`n}`n"
[IO.File]::WriteAllText($generated, $code, [Text.UTF8Encoding]::new($false))

$csc = Join-Path $env:WINDIR 'Microsoft.NET\Framework64\v4.0.30319\csc.exe'
$sources = (Join-Path $PSScriptRoot 'Launcher.cs'), (Join-Path $PSScriptRoot 'Updater.cs'), $generated
try {
    $ErrorActionPreference = 'Continue'
    & $csc /nologo /target:winexe /optimize+ /reference:System.IO.Compression.dll /reference:System.IO.Compression.FileSystem.dll "/win32icon:$(Join-Path $FirefoxApp 'branding\kivo\firefox.ico')" "/out:$Output" @sources
    $ErrorActionPreference = 'Stop'
    if ($LASTEXITCODE) { throw "launcher build failed ($LASTEXITCODE)" }
}
finally { Remove-Item $generated -Force -ErrorAction SilentlyContinue }
