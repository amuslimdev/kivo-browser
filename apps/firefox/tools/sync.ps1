<#
.SYNOPSIS
    بيجيب Firefox بالنسخة اللي في firefox.lock، ويحط عليه branding و patches بتوع Kivo.
.PARAMETER Update
    بيحدّث firefox.lock لآخر revision في الفرع (release) قبل الـ sync.
.PARAMETER NoBootstrap
    مايشغّلش mach bootstrap حتى لو الأدوات مش موجودة.
#>
param([switch] $Update, [switch] $NoBootstrap)
. "$PSScriptRoot\common.ps1"

if (-not (Test-Path (Join-Path $Source '.git'))) {
    New-Item -ItemType Directory -Force (Split-Path $Source) | Out-Null
    Invoke-Git init --quiet $Source
    Invoke-Git -C $Source remote add origin $Lock.repo
    Invoke-Git -C $Source config core.longpaths true
    Invoke-Git -C $Source config core.autocrlf false
}

if ($Update) {
    Invoke-Git -C $Source fetch --depth 50 origin $Lock.branch
    $revision = (& git -C $Source rev-parse FETCH_HEAD).Trim()
    $version = (& git -C $Source show "${revision}:browser/config/version_display.txt").Trim()
    $Lock.revision = $revision
    $Lock.version = $version
    # LF من غير BOM، زي باقي الـ repo.
    $json = ($Lock | ConvertTo-Json) -replace "`r`n", "`n"
    [IO.File]::WriteAllText((Join-Path $FirefoxApp 'firefox.lock'), "$json`n", [Text.UTF8Encoding]::new($false))
    Write-Host "firefox.lock: $version ($revision)"
}

# الـ artifact build بيدوّر على أقرب revision ليه ملفات جاهزة، فمحتاج شوية history مش commit واحد.
& git -C $Source cat-file -e "$($Lock.revision)^{commit}" 2>$null
if ($LASTEXITCODE) { Invoke-Git -C $Source fetch --depth 50 origin $Lock.revision }
Invoke-Git -C $Source checkout --quiet --force --detach $Lock.revision
# بيشيل نسخة الـ branding والملفات الجديدة من الـ sync اللي فات. الـ obj-* متجاهل في .gitignore بتاع Firefox، فالـ build بيفضل.
Invoke-Git -C $Source clean -fdq

$branding = Join-Path $FirefoxApp 'branding\kivo'
if (Test-Path $branding) {
    Copy-Item $branding (Join-Path $Source 'browser\branding\kivo') -Recurse -Force
} else {
    Write-Warning 'apps/firefox/branding/kivo is missing: run tools\make-branding.ps1, then sync again.'
}

# كود Kivo (G1 وبعده): ملفات جديدة بس، و patches بتربطها بـ Firefox.
$kivoDir = Join-Path $Source 'browser\components\kivo'
Copy-Item (Join-Path $FirefoxApp 'kivo') $kivoDir -Recurse -Force

# صفحة البداية (G2): build بتاع web/ui هو ملفات الـ extension المدمجة (kivo/jar.mn، builtin-addons/kivo-home).
$ui = Join-Path $Repo 'web\ui'
$ErrorActionPreference = 'Continue'
& pnpm --dir $ui build
$ErrorActionPreference = 'Stop'
if ($LASTEXITCODE) { throw "web/ui build failed ($LASTEXITCODE)" }
Copy-Item (Join-Path $ui 'dist') (Join-Path $kivoDir 'ui') -Recurse -Force

# خطوط الثيم في الواجهة من نفس ملفات الـ extension، فمصدرها واحد. fonts.css من الـ @font-face اللي في theme.css،
# بعنوان chrome://kivo-fonts (kivo/jar.mn) عشان صفحات الـ profiles بتسمح بـ chrome: بس.
$themeCss = [IO.File]::ReadAllText((Join-Path $ui 'src\theme.css'))
$faces = [regex]::Matches($themeCss, '(?s)@font-face\s*\{.*?\}') | ForEach-Object { $_.Value -replace "url\('/fonts/", "url('chrome://kivo-fonts/content/" }
$fontsCss = "/* Generated by apps/firefox/tools/sync.ps1 from web/ui/src/theme.css. */`n" + (($faces -join "`n`n") -replace "`r`n", "`n") + "`n"
[IO.File]::WriteAllText((Join-Path $kivoDir 'fonts.css'), $fontsCss, [Text.UTF8Encoding]::new($false))

$patches = Join-Path $FirefoxApp 'patches'
if (Test-Path $patches) {
    foreach ($patch in Get-ChildItem $patches -Filter *.patch | Sort-Object Name) {
        Invoke-Git -C $Source apply --whitespace=nowarn $patch.FullName
        Write-Host "patch: $($patch.Name)"
    }
}

if (-not $NoBootstrap -and -not (Test-Path (Join-Path $KivoSrc 'mozbuild\toolchains'))) {
    Invoke-Mach --no-interactive bootstrap --application-choice browser_artifact_mode --no-system-changes
}

Write-Host "Firefox $($Lock.version) synced to $Source"
